USE prece_digital;

CREATE TABLE IF NOT EXISTS controles_planificaciones (
  id                   VARCHAR(40)    NOT NULL PRIMARY KEY,
  planificacion_id     VARCHAR(40)    NOT NULL,
  docente_id           VARCHAR(40)    NOT NULL,
  materia_id           VARCHAR(40)    NOT NULL,
  curso_id             VARCHAR(40)    NOT NULL,
  division_id          VARCHAR(40)    NULL,
  anio                 SMALLINT       NOT NULL,
  periodo              ENUM('anual','primer_cuatrimestre','segundo_cuatrimestre','primer_trimestre','segundo_trimestre','tercer_trimestre') NULL,
  diseno_ids           JSON           NULL,
  contenidos           JSON           NOT NULL,
  correspondencia_diseno ENUM('total','parcial','no_coincide','no_evaluado') NOT NULL DEFAULT 'no_evaluado',
  observaciones        TEXT           NULL,
  estado               ENUM('pendiente','en_revision','aprobada','aprobada_con_observaciones','requiere_correccion','finalizada') NOT NULL DEFAULT 'pendiente',
  fecha_revision       DATE           NOT NULL,
  revisado_por         INT UNSIGNED   NULL,
  escuela_id           INT UNSIGNED   NOT NULL,
  creado_por           INT UNSIGNED   NULL,
  creado_en            DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_por      INT UNSIGNED   NULL,
  actualizado_en       DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY ix_ctl_planificacion (planificacion_id),
  KEY ix_ctl_docente (docente_id),
  KEY ix_ctl_materia (materia_id),
  KEY ix_ctl_curso (curso_id),
  KEY ix_ctl_periodo (anio, periodo),
  KEY ix_ctl_estado (estado),
  KEY ix_ctl_correspondencia (correspondencia_diseno),
  KEY ix_ctl_escuela (escuela_id),
  CONSTRAINT fk_ctl_planificacion FOREIGN KEY (planificacion_id) REFERENCES planificaciones_docentes(id) ON DELETE CASCADE,
  CONSTRAINT fk_ctl_materia FOREIGN KEY (materia_id) REFERENCES curriculum_materias(id) ON DELETE CASCADE,
  CONSTRAINT fk_ctl_escuela FOREIGN KEY (escuela_id) REFERENCES escuelas(id),
  CONSTRAINT fk_ctl_revisor FOREIGN KEY (revisado_por) REFERENCES usuarios(id),
  CONSTRAINT fk_ctl_creador FOREIGN KEY (creado_por) REFERENCES usuarios(id),
  CONSTRAINT fk_ctl_actualizador FOREIGN KEY (actualizado_por) REFERENCES usuarios(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS historial_controles_planificaciones (
  id                VARCHAR(40)    NOT NULL PRIMARY KEY,
  control_id        VARCHAR(40)    NOT NULL,
  planificacion_id  VARCHAR(40)    NOT NULL,
  tipo              ENUM('creacion','actualizacion','cambio_estado') NOT NULL,
  estado_anterior   ENUM('pendiente','en_revision','aprobada','aprobada_con_observaciones','requiere_correccion','finalizada') NULL,
  estado_nuevo      ENUM('pendiente','en_revision','aprobada','aprobada_con_observaciones','requiere_correccion','finalizada') NULL,
  cambios           JSON           NULL,
  comentario        TEXT           NULL,
  realizado_por     INT UNSIGNED   NULL,
  creado_en         DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY ix_chl_control (control_id),
  KEY ix_chl_planificacion (planificacion_id),
  KEY ix_chl_tipo (tipo),
  KEY ix_chl_fecha (creado_en),
  CONSTRAINT fk_chl_control FOREIGN KEY (control_id) REFERENCES controles_planificaciones(id) ON DELETE CASCADE,
  CONSTRAINT fk_chl_planificacion FOREIGN KEY (planificacion_id) REFERENCES planificaciones_docentes(id) ON DELETE CASCADE,
  CONSTRAINT fk_chl_realizado FOREIGN KEY (realizado_por) REFERENCES usuarios(id)
) ENGINE=InnoDB;
